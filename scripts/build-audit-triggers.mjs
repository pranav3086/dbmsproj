// Generates database/04_audit_triggers.sql from the table definitions in 01_schema.sql.
// MySQL triggers must name every column explicitly (there is no to_jsonb(row)), so the
// before/after row images are written out here instead of by hand. Run: npm run db:build-audit
import { readFileSync, writeFileSync } from 'node:fs'

const schema = readFileSync(new URL('../database/01_schema.sql', import.meta.url), 'utf8')

// table → which operations to audit
const audited = {
  user_roles: ['insert', 'update', 'delete'],
  staff_permissions: ['insert', 'update', 'delete'],
  doctor_applications: ['insert', 'update', 'delete'],
  departments: ['insert', 'update', 'delete'],
  doctors: ['insert', 'update', 'delete'],
  doctor_availability: ['insert', 'update', 'delete'],
  appointments: ['update'],
  consultations: ['insert', 'update', 'delete'],
  prescriptions: ['insert', 'update', 'delete'],
  prescription_items: ['insert', 'update', 'delete'],
  lab_reports: ['insert', 'update', 'delete'],
  lab_results: ['insert', 'update', 'delete'],
  observation_records: ['insert', 'update', 'delete'],
  medicines: ['insert', 'update', 'delete'],
  medication_orders: ['update'],
  profiles: ['update'],
}

function columnsOf(table) {
  const m = schema.match(new RegExp(`CREATE TABLE ${table} \\(([\\s\\S]*?)\\n\\);`))
  if (!m) throw new Error(`Table ${table} not found in 01_schema.sql`)
  return m[1]
    .split('\n')
    .map((l) => l.match(/^ {2}`?([a-z_]+)`?\s+([A-Z]+)/))
    .filter((x) => x && !['CONSTRAINT', 'INDEX', 'UNIQUE', 'PRIMARY'].includes(x[1].toUpperCase()))
    .filter((x) => !/ AS \(/.test(schema.split('\n').find((l) => l.startsWith(`  ${x[1]} `)) ?? ''))
    .map((x) => x[1])
}

const out = [
  '-- GENERATED by scripts/build-audit-triggers.mjs from 01_schema.sql — do not edit by hand.',
  '-- Row audit: every insert/update/delete on these tables is recorded in audit_logs with the',
  '-- acting user, the changed columns and the before/after row images (see audit_change()).',
  'USE a10_hospital;',
  '',
  'DELIMITER $$',
  '',
]
for (const [table, ops] of Object.entries(audited)) {
  const cols = columnsOf(table)
  const image = (row) => `JSON_OBJECT(${cols.map((c) => `'${c}', ${row}.\`${c}\``).join(', ')})`
  const idExpr = (row) => (cols.includes('id') ? `${row}.id` : `${row}.user_id`)
  for (const op of ops) {
    const oldImg = op === 'insert' ? 'NULL' : image('OLD')
    const newImg = op === 'delete' ? 'NULL' : image('NEW')
    const id = idExpr(op === 'delete' ? 'OLD' : 'NEW')
    out.push(`CREATE TRIGGER audit_${table}_${op} AFTER ${op.toUpperCase()} ON ${table}`)
    out.push(`FOR EACH ROW CALL audit_change('${op}', '${table}', ${id},`)
    out.push(`  ${oldImg},`)
    out.push(`  ${newImg})$$`)
    out.push('')
  }
}
out.push('DELIMITER ;', '')
writeFileSync(new URL('../database/04_audit_triggers.sql', import.meta.url), out.join('\n'))
console.log(`04_audit_triggers.sql: ${Object.values(audited).flat().length} triggers on ${Object.keys(audited).length} tables`)
